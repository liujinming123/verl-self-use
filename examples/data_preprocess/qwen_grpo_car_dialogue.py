if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--local_dir", default="/vepfs/group03/user/ljm/work/qwen_grpo/data/verl_format", help="The save directory for the preprocessed dataset.")
    parser.add_argument("--train_path", default="/vepfs/group03/user/ljm/work/qwen_grpo/data/train_data_all_0413.csv", help="The path to the training data.")
    parser.add_argument("--test_path", default="/vepfs/group03/user/ljm/work/qwen_grpo/data/test_data_0413.csv", help="The path to the test data.")
    
    args = parser.parse_args()
    
    data_source = "qwen_grpo_car_dialogue"
    ability = "dialogue_classification"
    
    def make_map_fn(split):
        def process_fn(row, idx):
            query = row["query"]
            label = int(row["label"])
            think_label = row["think_label"].strip()
            
            # 拆分合并标签：有不文明用语，产品体验差或者上下文中正常指令未响应
            MERGE_LABEL = "有不文明用语，产品体验差或者上下文中正常指令未响应"
            if think_label == MERGE_LABEL:
                # 匹配用户最后一句话之前车机是否有空回复
                # 正则逻辑：最后一个用户发言之前，存在"汽车语音助手: "后面全是空白的情况
                no_response_pattern = r"汽车语音助手:\s*\n(?=.*用户: [^\n]*(<疑似吐槽>|不文明用语|骂人|操|傻逼|滚|智障))"
                if re.search(no_response_pattern, query, flags=re.DOTALL):
                    # 车机有未响应的情况，拆分为指令未响应
                    think_label = "有不文明用语，上下文中正常指令未响应"
                else:
                    # 其他情况拆分为产品体验差
                    think_label = "有不文明用语，产品体验差"
            
            data = {
                "data_source": data_source,
                "prompt": [
                    {
                        "role": "system",
                        "content": SYSTEM_PROMPT,
                    },
                    {
                        "role": "user",
                        "content": user_prompt.format(text=query),
                    }
                ],
                "ability": ability,
                "reward_model": {
                    "style": "rule",
                    "ground_truth": label
                },
                "extra_info": {
                    "split": split,
                    "index": idx,
                    "think_label": think_label,
                },
            }
            return data
        
        return process_fn
    
    train_df = pd.read_csv(args.train_path)
    test_df = pd.read_csv(args.test_path)
    
    train_data = []
    test_data = []
    
    for idx, row in train_df.iterrows():
        train_data.append(make_map_fn("train")(row, idx))
    
    for idx, row in test_df.iterrows():
        test_data.append(make_map_fn("test")(row, idx))
    
    train_table = pa.Table.from_pandas(pd.DataFrame(train_data))
    test_table = pa.Table.from_pandas(pd.DataFrame(test_data))
    
    os.makedirs(args.local_dir, exist_ok=True)
    
    train_output_path = os.path.join(args.local_dir, "train_reason_v2.parquet")
